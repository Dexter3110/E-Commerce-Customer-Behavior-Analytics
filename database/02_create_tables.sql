-- Run this in pgAdmin's Query Tool after connecting to the `ecommerce_bda` database.
-- This creates the same eight application tables defined in backend/app/models.py.
-- Do not run this on a database already initialized with `alembic upgrade head`.

CREATE TABLE customers (
    customer_id INTEGER PRIMARY KEY,
    country VARCHAR(80) NOT NULL,
    first_order_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    last_order_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    order_count INTEGER NOT NULL,
    total_spent DOUBLE PRECISION NOT NULL
);

CREATE TABLE products (
    stock_code VARCHAR(40) PRIMARY KEY,
    description VARCHAR(255) NOT NULL
);

CREATE TABLE analytics_runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    params JSON NOT NULL,
    result JSON,
    error VARCHAR(2000),
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    started_at TIMESTAMP WITHOUT TIME ZONE,
    finished_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE orders (
    invoice_no VARCHAR(20) PRIMARY KEY,
    customer_id INTEGER REFERENCES customers(customer_id),
    invoice_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    country VARCHAR(80) NOT NULL,
    is_cancellation BOOLEAN NOT NULL,
    total_amount DOUBLE PRECISION NOT NULL
);

CREATE TABLE order_items (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_no VARCHAR(20) NOT NULL REFERENCES orders(invoice_no),
    stock_code VARCHAR(40) NOT NULL REFERENCES products(stock_code),
    quantity INTEGER NOT NULL,
    unit_price DOUBLE PRECISION NOT NULL,
    line_total DOUBLE PRECISION NOT NULL,
    CONSTRAINT ck_item_price_positive CHECK (unit_price > 0)
);

CREATE TABLE customer_segments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES analytics_runs(id) ON DELETE CASCADE,
    customer_id INTEGER NOT NULL REFERENCES customers(customer_id),
    recency INTEGER NOT NULL,
    frequency INTEGER NOT NULL,
    monetary DOUBLE PRECISION NOT NULL,
    r_score INTEGER,
    f_score INTEGER,
    m_score INTEGER,
    segment VARCHAR(40),
    cluster INTEGER,
    CONSTRAINT uq_segment_run_customer UNIQUE (run_id, customer_id)
);

CREATE TABLE association_rules (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES analytics_runs(id) ON DELETE CASCADE,
    antecedents JSON NOT NULL,
    consequents JSON NOT NULL,
    support DOUBLE PRECISION NOT NULL,
    confidence DOUBLE PRECISION NOT NULL,
    lift DOUBLE PRECISION NOT NULL
);

CREATE TABLE forecasts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES analytics_runs(id) ON DELETE CASCADE,
    date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    actual DOUBLE PRECISION,
    predicted DOUBLE PRECISION,
    baseline DOUBLE PRECISION,
    phase VARCHAR(10) NOT NULL
);

CREATE INDEX ix_customers_country ON customers(country);
CREATE INDEX ix_analytics_runs_run_type ON analytics_runs(run_type);
CREATE INDEX ix_analytics_runs_status ON analytics_runs(status);
CREATE INDEX ix_orders_customer_id ON orders(customer_id);
CREATE INDEX ix_orders_invoice_date ON orders(invoice_date);
CREATE INDEX ix_orders_country ON orders(country);
CREATE INDEX ix_orders_is_cancellation ON orders(is_cancellation);
CREATE INDEX ix_order_items_invoice_no ON order_items(invoice_no);
CREATE INDEX ix_order_items_stock_code ON order_items(stock_code);
CREATE INDEX ix_items_invoice_stock ON order_items(invoice_no, stock_code);
CREATE INDEX ix_customer_segments_run_id ON customer_segments(run_id);
CREATE INDEX ix_customer_segments_customer_id ON customer_segments(customer_id);
CREATE INDEX ix_customer_segments_segment ON customer_segments(segment);
CREATE INDEX ix_association_rules_run_id ON association_rules(run_id);
CREATE INDEX ix_association_rules_lift ON association_rules(lift);
CREATE INDEX ix_forecasts_run_id ON forecasts(run_id);
