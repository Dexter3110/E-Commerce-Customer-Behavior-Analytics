-- Run in pgAdmin Query Tool connected to `olist_ecommerce`.
-- Schema matches the nine CSV files in the Olist archive.
-- Run only once on a fresh database; do not run alongside the old UCI schema.

CREATE TABLE olist_customers (
    customer_id VARCHAR(32) PRIMARY KEY,
    customer_unique_id VARCHAR(32) NOT NULL,
    customer_zip_code_prefix VARCHAR(5) NOT NULL,
    customer_city VARCHAR(100) NOT NULL,
    customer_state VARCHAR(2) NOT NULL
);

CREATE TABLE olist_sellers (
    seller_id VARCHAR(32) PRIMARY KEY,
    seller_zip_code_prefix VARCHAR(5) NOT NULL,
    seller_city VARCHAR(100) NOT NULL,
    seller_state VARCHAR(2) NOT NULL
);

CREATE TABLE olist_products (
    product_id VARCHAR(32) PRIMARY KEY,
    product_category_name VARCHAR(100),
    product_name_lenght INTEGER,
    product_description_lenght INTEGER,
    product_photos_qty INTEGER,
    product_weight_g NUMERIC(10, 2),
    product_length_cm NUMERIC(10, 2),
    product_height_cm NUMERIC(10, 2),
    product_width_cm NUMERIC(10, 2)
);

CREATE TABLE product_category_name_translation (
    product_category_name VARCHAR(100) PRIMARY KEY,
    product_category_name_english VARCHAR(100) NOT NULL
);

CREATE TABLE olist_orders (
    order_id VARCHAR(32) PRIMARY KEY,
    customer_id VARCHAR(32) NOT NULL REFERENCES olist_customers(customer_id),
    order_status VARCHAR(30) NOT NULL,
    order_purchase_timestamp TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    order_approved_at TIMESTAMP WITHOUT TIME ZONE,
    order_delivered_carrier_date TIMESTAMP WITHOUT TIME ZONE,
    order_delivered_customer_date TIMESTAMP WITHOUT TIME ZONE,
    order_estimated_delivery_date TIMESTAMP WITHOUT TIME ZONE
);

CREATE TABLE olist_order_items (
    order_id VARCHAR(32) NOT NULL REFERENCES olist_orders(order_id),
    order_item_id INTEGER NOT NULL,
    product_id VARCHAR(32) NOT NULL REFERENCES olist_products(product_id),
    seller_id VARCHAR(32) NOT NULL REFERENCES olist_sellers(seller_id),
    shipping_limit_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    price NUMERIC(12, 2) NOT NULL,
    freight_value NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (order_id, order_item_id)
);

CREATE TABLE olist_order_payments (
    order_id VARCHAR(32) NOT NULL REFERENCES olist_orders(order_id),
    payment_sequential INTEGER NOT NULL,
    payment_type VARCHAR(30) NOT NULL,
    payment_installments INTEGER NOT NULL,
    payment_value NUMERIC(12, 2) NOT NULL,
    PRIMARY KEY (order_id, payment_sequential)
);

CREATE TABLE olist_order_reviews (
    review_id VARCHAR(32) NOT NULL,
    order_id VARCHAR(32) NOT NULL REFERENCES olist_orders(order_id),
    review_score SMALLINT NOT NULL CHECK (review_score BETWEEN 1 AND 5),
    review_comment_title TEXT,
    review_comment_message TEXT,
    review_creation_date TIMESTAMP WITHOUT TIME ZONE,
    review_answer_timestamp TIMESTAMP WITHOUT TIME ZONE,
    PRIMARY KEY (review_id, order_id)
);

-- Geolocation contains multiple observations per postal prefix, so it has its
-- own generated key and does not join to orders through a unique postal code.
CREATE TABLE olist_geolocation (
    geolocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    geolocation_zip_code_prefix VARCHAR(5) NOT NULL,
    geolocation_lat DOUBLE PRECISION,
    geolocation_lng DOUBLE PRECISION,
    geolocation_city VARCHAR(100),
    geolocation_state VARCHAR(2)
);

CREATE INDEX ix_olist_customers_unique_id ON olist_customers(customer_unique_id);
CREATE INDEX ix_olist_customers_state ON olist_customers(customer_state);
CREATE INDEX ix_olist_orders_customer_id ON olist_orders(customer_id);
CREATE INDEX ix_olist_orders_purchase_timestamp ON olist_orders(order_purchase_timestamp);
CREATE INDEX ix_olist_orders_status ON olist_orders(order_status);
CREATE INDEX ix_olist_order_items_product_id ON olist_order_items(product_id);
CREATE INDEX ix_olist_order_items_seller_id ON olist_order_items(seller_id);
CREATE INDEX ix_olist_order_payments_type ON olist_order_payments(payment_type);
CREATE INDEX ix_olist_order_reviews_score ON olist_order_reviews(review_score);
CREATE INDEX ix_olist_sellers_state ON olist_sellers(seller_state);
CREATE INDEX ix_olist_products_category ON olist_products(product_category_name);
CREATE INDEX ix_olist_geolocation_zip ON olist_geolocation(geolocation_zip_code_prefix);
