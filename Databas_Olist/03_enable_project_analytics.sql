-- Run this once in pgAdmin Query Tool on your loaded Olist database.
-- It creates read-only compatibility views so the existing dashboard and
-- analytics can read Olist, plus tables for saved analytics results.
-- It does not change or delete the nine imported Olist source tables.

CREATE TABLE IF NOT EXISTS analytics_customer_map (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_unique_id VARCHAR(32) NOT NULL UNIQUE
);

INSERT INTO analytics_customer_map (customer_unique_id)
SELECT DISTINCT customer_unique_id
FROM olist_customers
WHERE customer_unique_id IS NOT NULL
ON CONFLICT (customer_unique_id) DO NOTHING;

CREATE OR REPLACE VIEW customers AS
SELECT cm.customer_id,
       COALESCE(MAX(oc.customer_state), 'Unknown')::VARCHAR(80) AS country,
       MIN(o.order_purchase_timestamp) AS first_order_date,
       MAX(o.order_purchase_timestamp) AS last_order_date,
       COUNT(DISTINCT o.order_id)::INTEGER AS order_count,
       COALESCE(SUM(oi.price), 0)::DOUBLE PRECISION AS total_spent
FROM analytics_customer_map cm
JOIN olist_customers oc ON oc.customer_unique_id = cm.customer_unique_id
JOIN olist_orders o ON o.customer_id = oc.customer_id AND o.order_status = 'delivered'
JOIN olist_order_items oi ON oi.order_id = o.order_id
GROUP BY cm.customer_id;

CREATE OR REPLACE VIEW products AS
SELECT p.product_id::VARCHAR(40) AS stock_code,
       LEFT(COALESCE(t.product_category_name_english, p.product_category_name, 'Uncategorized'), 255)::VARCHAR(255) AS description
FROM olist_products p
LEFT JOIN product_category_name_translation t
  ON t.product_category_name = p.product_category_name;

CREATE OR REPLACE VIEW orders AS
SELECT o.order_id AS invoice_no,
       cm.customer_id,
       o.order_purchase_timestamp AS invoice_date,
       COALESCE(c.customer_state, 'Unknown')::VARCHAR(80) AS country,
       (o.order_status IN ('canceled', 'unavailable')) AS is_cancellation,
       COALESCE(t.total_amount, 0)::DOUBLE PRECISION AS total_amount
FROM olist_orders o
JOIN olist_customers c ON c.customer_id = o.customer_id
JOIN analytics_customer_map cm ON cm.customer_unique_id = c.customer_unique_id
LEFT JOIN (
    SELECT order_id, SUM(price) AS total_amount
    FROM olist_order_items
    GROUP BY order_id
) t ON t.order_id = o.order_id
WHERE o.order_status IN ('delivered', 'canceled', 'unavailable');

CREATE OR REPLACE VIEW order_items AS
SELECT ROW_NUMBER() OVER (ORDER BY oi.order_id, oi.order_item_id)::BIGINT AS id,
       oi.order_id AS invoice_no,
       oi.product_id::VARCHAR(40) AS stock_code,
       1::INTEGER AS quantity,
       oi.price::DOUBLE PRECISION AS unit_price,
       oi.price::DOUBLE PRECISION AS line_total
FROM olist_order_items oi;

CREATE TABLE IF NOT EXISTS analytics_runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_type VARCHAR(30) NOT NULL,
    status VARCHAR(20) NOT NULL,
    params JSON NOT NULL,
    result JSON,
    error VARCHAR(2000),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMP WITHOUT TIME ZONE,
    finished_at TIMESTAMP WITHOUT TIME ZONE
);
CREATE INDEX IF NOT EXISTS ix_analytics_runs_run_type ON analytics_runs(run_type);
CREATE INDEX IF NOT EXISTS ix_analytics_runs_status ON analytics_runs(status);

CREATE TABLE IF NOT EXISTS customer_segments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES analytics_runs(id) ON DELETE CASCADE,
    customer_id INTEGER NOT NULL,
    recency INTEGER NOT NULL,
    frequency INTEGER NOT NULL,
    monetary DOUBLE PRECISION NOT NULL,
    r_score INTEGER,
    f_score INTEGER,
    m_score INTEGER,
    segment VARCHAR(40),
    cluster INTEGER,
    CONSTRAINT uq_segment_run_customer UNIQUE (run_id, customer_id)
);
CREATE INDEX IF NOT EXISTS ix_customer_segments_run_id ON customer_segments(run_id);
CREATE INDEX IF NOT EXISTS ix_customer_segments_customer_id ON customer_segments(customer_id);
CREATE INDEX IF NOT EXISTS ix_customer_segments_segment ON customer_segments(segment);

CREATE TABLE IF NOT EXISTS association_rules (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES analytics_runs(id) ON DELETE CASCADE,
    antecedents JSON NOT NULL,
    consequents JSON NOT NULL,
    support DOUBLE PRECISION NOT NULL,
    confidence DOUBLE PRECISION NOT NULL,
    lift DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_association_rules_run_id ON association_rules(run_id);
CREATE INDEX IF NOT EXISTS ix_association_rules_lift ON association_rules(lift);

CREATE TABLE IF NOT EXISTS forecasts (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES analytics_runs(id) ON DELETE CASCADE,
    date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    actual DOUBLE PRECISION,
    predicted DOUBLE PRECISION,
    baseline DOUBLE PRECISION,
    phase VARCHAR(10) NOT NULL
);
CREATE INDEX IF NOT EXISTS ix_forecasts_run_id ON forecasts(run_id);

-- Quick check: views should report delivered-order data and saved-run tables exist.
SELECT 'customers' AS object_name, COUNT(*) AS row_count FROM customers
UNION ALL SELECT 'products', COUNT(*) FROM products
UNION ALL SELECT 'orders', COUNT(*) FROM orders
UNION ALL SELECT 'order_items', COUNT(*) FROM order_items
ORDER BY object_name;
